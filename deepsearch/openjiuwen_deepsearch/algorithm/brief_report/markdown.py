"""Brief 章节 Markdown 的引用和标题确定性校验。"""

import re

from openjiuwen_deepsearch.algorithm.brief_report.html_content import preprocess_markdown
from openjiuwen_deepsearch.algorithm.brief_report.models import BriefSection
from openjiuwen_deepsearch.common.common_constants import ENGLISH

CITATION_PATTERN = re.compile(r"\[\s*citation:\s*(\d+)\s*\]")
REFERENCE_LINE_PATTERN = re.compile(r"^\[\d+\]\.\s+\[")
FENCE_PATTERN = re.compile(r"^\s{0,3}(`{3,}|~{3,})")


def _separate_reference_lines(markdown: str) -> str:
    """分隔相邻参考文章，使 Markdown 渲染器逐条显示。

    Args:
        markdown: 已规范化引用的报告正文。

    Returns:
        相邻参考条目之间增加空行后的正文；围栏代码保持不变。
    """
    lines = markdown.splitlines(keepends=True)
    result: list[str] = []
    in_fence = False
    fence_marker = ""
    previous_reference = False
    for line in lines:
        fence = FENCE_PATTERN.match(line)
        if fence:
            marker = fence.group(1)
            if not in_fence:
                in_fence, fence_marker = True, marker
            elif (
                marker[0] == fence_marker[0]
                and len(marker) >= len(fence_marker)
                and not line[fence.end():].strip()
            ):
                in_fence, fence_marker = False, ""
        is_reference = not in_fence and bool(REFERENCE_LINE_PATTERN.match(line))
        if previous_reference and is_reference:
            result.append("\n")
        result.append(line)
        previous_reference = is_reference
    return "".join(result)


def select_brief_markdown(
    *,
    checked: object,
    assembled: object,
    response_content: object,
    response_content_type: object,
) -> str:
    """按引用校验、拼装和主响应的顺序选择可用 Markdown。

    Args:
        checked: 引用校验后的报告正文。
        assembled: 引用校验前拼装的报告正文。
        response_content: 现有主响应正文。
        response_content_type: 主响应类型；空字符串按 Markdown 处理。

    Returns:
        第一个非空白字符串；没有可用 Markdown 时返回空字符串。
    """
    candidates = [checked, assembled]
    if response_content_type in ("", "text/markdown"):
        candidates.append(response_content)
    return next((value for value in candidates if isinstance(value, str) and value.strip()), "")


def format_brief_markdown(markdown: str, language: str | None) -> str:
    """规范化 Brief Markdown 的引用并追加一次 AI 声明。

    Args:
        markdown: 引用校验后的报告正文，或校验跳过时的拼装正文。
        language: 报告语言标识。

    Returns:
        可独立阅读的 Markdown；正文为空时返回空字符串。
    """
    notice = "> This research report was generated by AI." if language == ENGLISH else "> 本研究报告由 AI 生成。"
    markdown = markdown.rstrip()
    # 先移除已有尾部声明，避免补充参考文章后重复追加声明。
    if markdown.endswith(notice):
        markdown = markdown[:-len(notice)].rstrip()
        if markdown.endswith("\n\n---"):
            markdown = markdown[:-5].rstrip()
    if not markdown:
        return ""
    cleaned = _separate_reference_lines(preprocess_markdown(markdown).cleaned_markdown).rstrip()
    return f"{cleaned}\n\n---\n\n{notice}"


def _normalize_headings(markdown: str, section: BriefSection) -> str:
    """规范化章节标题层级，并保留 fenced code 内的原始文本。"""
    normalized: list[str] = []
    in_fence = False
    fence_marker = ""
    has_section_heading = False
    for line in markdown.splitlines():
        fence = re.match(r"^\s*(`{3,}|~{3,})", line)
        if fence:
            marker = fence.group(1)[0]
            if not in_fence:
                in_fence, fence_marker = True, marker
            elif marker == fence_marker:
                in_fence, fence_marker = False, ""
            normalized.append(line)
        elif in_fence:
            normalized.append(line)
        else:
            match = re.match(r"^(#{1,6})\s+(.+)$", line)
            if not match:
                normalized.append(line)
            elif len(match.group(1)) == 1:
                if not has_section_heading:
                    normalized.append(f"## {section.id} {section.title}")
                    has_section_heading = True
            else:
                normalized.append(f"### {match.group(2)}")
    if not has_section_heading:
        normalized.insert(0, f"## {section.id} {section.title}")
    return "\n".join(normalized).strip()


def sanitize_brief_chapter(
    markdown: str,
    section: BriefSection,
    allowed_citations: set[int],
) -> str:
    """规范化章节边界，并删除无效引用。

    Args:
        markdown: LLM 输出的原始章节 Markdown。
        section: 当前章节的结构化合同。
        allowed_citations: 本章可使用的引用编号。

    Returns:
        保留原有正文、仅进行引用和边界清理后的章节 Markdown。
    """
    normalized = _normalize_headings(markdown, section)
    normalized = CITATION_PATTERN.sub(
        lambda match: match.group(0) if int(match.group(1)) in allowed_citations else "",
        normalized,
    )
    return re.sub(r"\n{3,}", "\n\n", normalized).strip()
