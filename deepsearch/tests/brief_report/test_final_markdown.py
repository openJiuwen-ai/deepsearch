@pytest.mark.asyncio
async def test_tracing_error_uses_assembled_report_and_preserves_error():
    result, _ = await run_end(
        {"response_content": "<html></html>", "response_content_type": "text/html", "exception_info": "trace failed"},
        {"report_type": "brief"},
        {"checked_trace_source_report_content": "  ", "report_content": "# Assembled"},
    )
    assert result["response_markdown"].startswith("# Assembled")
    assert result["exception_info"] == "trace failed"


@pytest.mark.asyncio
async def test_cancellation_is_not_swallowed_during_markdown_preparation(monkeypatch):
    def stop(*_):
        raise asyncio.CancelledError()

    monkeypatch.setattr(brief_result, "format_brief_markdown", stop)
    with pytest.raises(asyncio.CancelledError):
        await run_end({"response_content": "<html></html>", "response_content_type": "text/html"},
                      {"report_type": "brief"}, {"report_content": "# Report"})


@pytest.mark.asyncio
async def test_final_markdown_survives_sdk_stream():
    result, session = await run_end(
        {"response_content": "<html></html>", "response_content_type": "text/html", "exception_info": ""},
        {"report_type": "brief"}, {"report_content": "# Report"},
    )
    event = session.write_custom_stream.await_args_list[0].args[0]
    sdk_message = DeepresearchAgent._build_output_message("conversation", SimpleNamespace(**event))

    assert json.loads(json.loads(sdk_message)["content"])["response_markdown"] == result["response_markdown"]
