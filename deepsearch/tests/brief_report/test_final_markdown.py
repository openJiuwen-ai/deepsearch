from types import SimpleNamespace
from unittest.mock import AsyncMock, Mock

import pytest
from openjiuwen.core.session.node import Session

from openjiuwen_deepsearch.framework.openjiuwen.agent import brief_result, main_graph_nodes
from openjiuwen_deepsearch.framework.openjiuwen.agent.search_context import FinalResult, Report, ReportTypePolicy
from openjiuwen_deepsearch.framework.openjiuwen.agent.workflow import DeepresearchAgent


async def run_end(result, policy, report, language="zh-CN"):
    values = {
        "search_context.final_result": result,
        "search_context.report_type_policy": policy,
        "search_context.current_report": report,
        "search_context.language": language,
    }
    session = AsyncMock(spec=Session)
    session.get_global_state.side_effect = values.get
    session.update_global_state = Mock()
    session.write_custom_stream = AsyncMock()
    output = await main_graph_nodes.EndNode().invoke({}, session, None)
    return json.loads(output["final_result"]), session


@pytest.mark.asyncio
async def test_brief_html_returns_clean_checked_markdown_and_streams_it():
    checked = (
        "# 报告\n\n## 核心摘要\n\n结论 [checked_citation:3][[1]](https://example.com/a)。"
        "\n\n## 参考文章\n\n[1]. [来源](https://example.com/a)"
    )
    result, session = await run_end(
        {"response_content": "<html>图表</html>", "response_content_type": "text/html", "exception_info": ""},
        ReportTypePolicy(report_type="brief"),
        Report(report_content="旧正文", checked_trace_source_report_content=checked),
    )
    assert result["response_content"] == "<html>图表</html>"
    assert "[checked_citation:" not in result["response_markdown"]
    assert "[[1]](https://example.com/a)" in result["response_markdown"]
    assert result["response_markdown"].endswith("> 本研究报告由 AI 生成。")
    assert json.loads(session.write_custom_stream.await_args_list[0].args[0]["content"]) == result
    session.update_global_state.assert_any_call({"search_context.final_result.response_markdown": result["response_markdown"]})


@pytest.mark.asyncio
async def test_brief_fallback_and_english_notice_are_idempotent():
    source = "# Report\n\n[source_tracer_result][Source](https://example.com/a)\n\n---\n\n> This research report was generated by AI."
    result, _ = await run_end(
        {"response_content": source, "response_content_type": "text/markdown", "warning_info": "HTML failed", "exception_info": ""},
        {"report_type": "brief"}, {}, "en",
    )
    md = result["response_markdown"]
    assert "[source_tracer_result]" not in md
    assert "[1]. [Source](https://example.com/a)" in md
    assert md.count("This research report was generated by AI.") == 1
    assert md.endswith("> This research report was generated by AI.")
    assert result["warning_info"] == "HTML failed"


@pytest.mark.asyncio
async def test_professional_upgrade_does_not_return_brief_markdown():
    result, _ = await run_end(
        {"response_content": "# Professional", "response_markdown": "old brief", "exception_info": ""},
        SimpleNamespace(report_type="professional"),
        {"report_content": "old brief"},
    )
    assert result["response_markdown"] == ""
    assert result["response_content"].startswith("# Professional")


@pytest.mark.asyncio
async def test_normalization_failure_preserves_html_and_existing_error(monkeypatch):
    def fail(*_):
        raise ValueError("sensitive text")

    monkeypatch.setattr(brief_result, "format_brief_markdown", fail)
    result, session = await run_end(
        {"response_content": "<html></html>", "response_content_type": "text/html", "warning_info": "previous", "exception_info": "trace failed"},
        {"report_type": "brief"}, {"report_content": "# Report"},
    )
    assert result["response_content"] == "<html></html>"
    assert result["response_markdown"] == ""
    assert result["warning_info"] == "previous\nbrief markdown output unavailable"
    assert result["exception_info"] == "trace failed"
    assert session.write_custom_stream.await_args_list[0].args[0]["event"] == "error"


